    suspend fun ensure(db: FitPlanDatabase): Int {
        var added = 0
        db.withTransaction {
            for (c in all) {
                val fullName = "${c.emoji}${c.name}"
                if (db.exerciseDao().idByName(fullName) == null) {
                    db.exerciseDao().insert(
                        Exercise(
                            name = fullName,
                            muscleGroup = c.muscle,
                            equipment = c.equipment,
                            note = note(c.cue, c.error),
                            isCustom = false
                        )
                    )
                    added++
                }
            }
        }
        return added
    }
