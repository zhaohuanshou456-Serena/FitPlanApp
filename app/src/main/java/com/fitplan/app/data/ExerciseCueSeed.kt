    suspend fun ensure(db: FitPlanDatabase): Int {
        var addedOrUpdated = 0
        db.withTransaction {
            for (c in all) {
                val fullName = "${c.emoji}${c.name}"
                val existingId = db.exerciseDao().idByName(fullName)
                if (existingId == null) {
                    db.exerciseDao().insert(
                        Exercise(
                            name = fullName,
                            muscleGroup = c.muscle,
                            equipment = c.equipment,
                            note = note(c.cue, c.error),
                            isCustom = false
                        )
                    )
                    addedOrUpdated++
                } else {
                    db.exerciseDao().update(
                        Exercise(
                            id = existingId,
                            name = fullName,
                            muscleGroup = c.muscle,
                            equipment = c.equipment,
                            note = note(c.cue, c.error),
                            isCustom = false
                        )
                    )
                    addedOrUpdated++
                }
            }
        }
        return addedOrUpdated
    }
